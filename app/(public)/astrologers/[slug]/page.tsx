import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { PersonaProfile } from "@/components/astrologers/PersonaProfile";
import { appConfig } from "@/lib/config";
import { SEED_COUNSELLORS } from "@/lib/constants";
import { firstName } from "@/lib/format";
import { jsonLd, pageMetadata } from "@/lib/seo";

type Props = { params: Promise<{ slug: string }> };

// One prerendered page per persona; unknown slugs are a 404.
export const dynamicParams = false;
export function generateStaticParams() {
    return SEED_COUNSELLORS.map((c) => ({ slug: c.slug }));
}

const find = (slug: string) => SEED_COUNSELLORS.find((c) => c.slug === slug);

export async function generateMetadata({ params }: Props): Promise<Metadata> {
    const c = find((await params).slug);
    if (!c) return {};
    return pageMetadata({
        title: `${c.name}, AI astrologer persona`,
        description: `${firstName(c.name)} is an AI astrologer persona (${c.specialties.join(", ")}) from ${c.hometown}. ${c.tagline} Call or chat in ${c.languages.slice(0, 2).join(" or ")}.`,
        path: `/astrologers/${c.slug}`,
        ownImage: true,
    });
}

export default async function AstrologerPage({ params }: Props) {
    const c = find((await params).slug);
    if (!c) notFound();
    const url = `${appConfig.url}/astrologers/${c.slug}`;

    // A persona is not a person, so it is described as a Service offered by Kosmo, not a Person.
    const structuredData = {
        "@context": "https://schema.org",
        "@graph": [
            {
                "@type": "WebPage",
                "@id": url,
                url,
                name: `${c.name}, AI astrologer persona`,
                inLanguage: "en-IN",
                isPartOf: { "@id": `${appConfig.url}/#website` },
                primaryImageOfPage: `${appConfig.url}${c.portrait}`,
                mainEntity: {
                    "@type": "Service",
                    name: `${c.name} (AI astrology persona)`,
                    serviceType: "AI astrology conversation",
                    description: `${c.name} is an AI persona, not a real person. Replies are generated by a language model. ${c.tagline}`,
                    provider: { "@id": `${appConfig.url}/#organization` },
                    availableLanguage: c.languages,
                    image: `${appConfig.url}${c.portrait}`,
                    areaServed: "IN",
                },
            },
            {
                "@type": "BreadcrumbList",
                itemListElement: [
                    { "@type": "ListItem", position: 1, name: "Astrologers", item: `${appConfig.url}/astrologers` },
                    { "@type": "ListItem", position: 2, name: c.name, item: url },
                ],
            },
        ],
    };

    return (
        <>
            <script type="application/ld+json" dangerouslySetInnerHTML={jsonLd(structuredData)} />
            <PersonaProfile c={c} back={{ href: "/astrologers", label: "All astrologers" }} />
        </>
    );
}
