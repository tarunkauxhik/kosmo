import { Badge } from "@/components/ui/badge";
import { cn } from "@/lib/utils";

// Every persona in Kosmo is an AI. This badge says so wherever a persona appears.
// Plain markup (no tooltip script) so it costs nothing on prerendered pages.
export function AiBadge({ className }: { className?: string }) {
    return (
        <Badge
            variant="outline"
            title="Not a real person. Replies are generated by a language model."
            className={cn("border-transparent bg-brand/10 font-medium text-brand", className)}
        >
            AI persona
        </Badge>
    );
}
